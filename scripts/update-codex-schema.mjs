#!/usr/bin/env node
// Regenerates test/fixtures/codex-app-server-schema.json from the installed Desktop Codex.
// Opt-in: run it after a Codex update, review the diff, then `npm run check`.
// It only asks Codex to write schema files; it never starts an app-server session.
import {execFile} from 'node:child_process';
import {mkdtemp, readFile, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {promisify} from 'node:util';
import {resolveCodex} from '../lib/codex-client.mjs';

const exec = promisify(execFile);
const fixture = fileURLToPath(new URL('../test/fixtures/codex-app-server-schema.json', import.meta.url));

// Every app-server request chill-agent sends (grep `.request('` in lib/ and bin/); test/codex-contract.test.mjs fails when one is missing here.
// Value: [Params definition, Response definition]. v2 methods live under definitions.v2, initialize at the top level.
export const METHODS = {
  initialize: ['InitializeParams', 'InitializeResponse'],
  'thread/read': ['ThreadReadParams', 'ThreadReadResponse'],
  'thread/turns/list': ['ThreadTurnsListParams', 'ThreadTurnsListResponse'],
  'thread/items/list': ['ThreadItemsListParams', 'ThreadItemsListResponse'],
  'thread/queue/list': ['ThreadQueueListParams', 'ThreadQueueListResponse'],
  'thread/queue/add': ['ThreadQueueAddParams', 'ThreadQueueAddResponse'],
  'model/list': ['ModelListParams', 'ModelListResponse'],
  'account/rateLimits/read': ['GetAccountRateLimitsParams', 'GetAccountRateLimitsResponse'],
};

const refName = ref => ref.slice('#/definitions/'.length).split('/');
const lookup = (root, ref) => refName(ref).reduce((node, key) => node?.[key], root.definitions);

function collect(node, refs) {
  if (Array.isArray(node)) { for (const item of node) collect(item, refs); return; }
  if (!node || typeof node !== 'object') return;
  if (typeof node.$ref === 'string') refs.add(node.$ref);
  for (const value of Object.values(node)) collect(value, refs);
}

function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (!node || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node).sort(([a], [b]) => a < b ? -1 : 1)) {
    if (key === 'description') continue;
    out[key] = key === 'properties' || key === 'definitions' ? Object.fromEntries(Object.entries(value).sort(([a], [b]) => a < b ? -1 : 1).map(([name, child]) => [name, strip(child)])) : strip(value);
  }
  return out;
}

export function extract(bundle, requests) {
  const definitions = {};
  const methods = {};
  const seen = new Set();
  const take = ref => {
    if (seen.has(ref)) return;
    seen.add(ref);
    const names = refName(ref);
    const value = lookup(bundle, ref);
    if (!value) throw new Error(`Codex schema lacks ${ref}`);
    let target = definitions;
    for (const name of names.slice(0, -1)) target = target[name] ??= {};
    target[names.at(-1)] = value;
    const inner = new Set();
    collect(value, inner);
    for (const next of inner) take(next);
  };
  for (const [method, [params, response]] of Object.entries(METHODS)) {
    const request = requests.oneOf.find(entry => entry.properties.method.enum[0] === method);
    if (!request) throw new Error(`Codex no longer has the ${method} request`);
    const named = JSON.stringify(request.properties.params);
    if (!named.includes(`/${params}"`)) throw new Error(`${method} params are no longer ${params}: ${named}`);
    const resolve = name => bundle.definitions.v2?.[name] ? `#/definitions/v2/${name}` : bundle.definitions[name] ? `#/definitions/${name}` : null;
    const paramsRef = resolve(params), responseRef = resolve(response);
    if (!paramsRef || !responseRef) throw new Error(`Codex schema lacks ${params} or ${response}`);
    methods[method] = {params: {$ref: paramsRef}, response: {$ref: responseRef}};
    take(paramsRef);
    take(responseRef);
  }
  return strip({definitions, methods});
}

async function main() {
  const codex = await resolveCodex();
  const directory = await mkdtemp(join(tmpdir(), 'codex-schema-'));
  try {
    const command = 'app-server generate-json-schema --experimental';
    await exec(codex.path, [...command.split(' '), '--out', directory], {timeout: 60000});
    const bundle = JSON.parse(await readFile(join(directory, 'codex_app_server_protocol.schemas.json'), 'utf8'));
    const requests = JSON.parse(await readFile(join(directory, 'ClientRequest.json'), 'utf8'));
    const result = {
      $comment: `Generated by scripts/update-codex-schema.mjs. Do not edit by hand. Trimmed to the requests chill-agent sends, descriptions removed.`,
      codex: {version: codex.version, command: `codex ${command} --out <dir>`},
      ...extract(bundle, requests),
    };
    await writeFile(fixture, `${JSON.stringify(result, null, 1)}\n`);
    console.log(`Wrote ${fixture} from ${codex.version}`);
  } finally { await rm(directory, {recursive: true, force: true}); }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
