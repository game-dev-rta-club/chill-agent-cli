import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {fileURLToPath} from 'node:url';
const execute=promisify(execFile),store=new URL('../lib/goal-store.mjs',import.meta.url).href,search=new URL('../lib/workspace-search.mjs',import.meta.url).href;
for(const backend of ['json','sqlite'])test(`${backend} search finds visible Goals, Comments, Letters and Deliverables`,async t=>{
 const root=await mkdtemp(join(tmpdir(),'chill-search-'));t.after(()=>rm(root,{recursive:true,force:true,maxRetries:10}));
 const code=`
 import assert from 'node:assert/strict';import {writeFile} from 'node:fs/promises';
 import * as s from ${JSON.stringify(store)};import {searchWorkspace,searchTerms} from ${JSON.stringify(search)};
 await s.createGoal({title:'Calm search box',scope:'Find old notes'});
 await s.createGoal({title:'Release',parentId:'1'});
 const hidden=await s.createGoal({title:'Old calm root'});
 const comment=await s.appendFeedback({goalId:'2',text:'The CALM button sits in the header…'});
 const letter=await s.appendAgentComment({goalId:'2',type:'letter',title:'Which calm color?',text:'Pick one'});
 const gone=await s.appendAgentComment({goalId:'2',type:'comment',text:'calm draft to delete'});await s.deleteAgentComment('2',gone.id);
 await s.appendFeedback({goalId:hidden.id,text:'calm but archived'});await s.updateGoal(hidden.id,{archived:true});
 await writeFile(s.briefPath('2','markdown'),'# Plan\\n\\nA **calm** header…\\n');await s.updateBrief('2','markdown');
 assert.deepEqual(searchTerms('  ＣＡＬＭ\\u3000header calm '),['calm','header']);
 const all=await searchWorkspace('calm');
 assert.deepEqual(all.results.map(r=>[r.kind,r.goalId]),[['goal','1'],['deliverable','2'],['letter','2'],['comment','2']]);
 assert.equal(all.more,false);
 const found=all.results.find(r=>r.kind==='comment');
 assert.equal(found.eventId,comment.id);assert.equal(found.number,1);assert.equal(found.author,'user');assert.equal(found.goalTitle,'Release');
 assert.equal(found.snippet,'The CALM button sits in the header…','shows the text as written');
 assert.equal(all.results.find(r=>r.kind==='letter').eventId,letter.id);
 assert.equal(all.results.find(r=>r.kind==='deliverable').version,1);
 assert.deepEqual((await searchWorkspace('calm header')).results.map(r=>r.kind),['deliverable','comment'],'every word must appear');
 assert.deepEqual((await searchWorkspace('   ')).results,[]);
 for(let i=0;i<60;i++)await s.appendFeedback({goalId:'1',text:'needle '+i});
 await new Promise(resolve=>setTimeout(resolve,3100));
 const many=await searchWorkspace('needle');assert.equal(many.results.length,50);assert.equal(many.more,true);assert.equal(many.results[0].snippet,'needle 59');
 const long='x'.repeat(200)+'needle'+'y'.repeat(200);await s.appendFeedback({goalId:'1',text:long});
 await new Promise(resolve=>setTimeout(resolve,3100));
 const cut=(await searchWorkspace('needle')).results[0].snippet;assert.ok(cut.startsWith('…')&&cut.endsWith('…')&&cut.includes('needle'));assert.ok(cut.length<130);
 `;
 const result=await execute(process.execPath,['--no-warnings','--input-type=module','-e',code],{env:{...process.env,CHILL_AGENT_DATA_DIR:root,CHILL_AGENT_STORAGE:backend}});
 assert.equal(result.stdout,'');
});
test('Web answers GET /api/search and refuses other methods',async t=>{
 const {spawn}=await import('node:child_process'),{once}=await import('node:events');
 const root=await mkdtemp(join(tmpdir(),'chill-search-web-')),env={...process.env,CHILL_AGENT_DATA_DIR:root,PORT:'0',CHILL_AGENT_EXTENSIONS:'none'};
 const cli=fileURLToPath(new URL('../bin/chill-agent.mjs',import.meta.url));
 await execute(process.execPath,[cli,'create','--title','Searchable calm Goal'],{env});
 const server=spawn(process.execPath,[fileURLToPath(new URL('../server.mjs',import.meta.url)),'--local'],{env,stdio:['ignore','pipe','pipe']});
 t.after(async()=>{if(server.exitCode===null){server.kill();await once(server,'exit');}await rm(root,{recursive:true,force:true,maxRetries:10});});
 const url=await new Promise((resolve,reject)=>{server.stdout.on('data',b=>{const m=String(b).match(/http:\/\/127\.0\.0\.1:\d+/);if(m)resolve(m[0]);});server.on('exit',code=>reject(Error(`Early exit ${code}`)));});
 const found=await (await fetch(`${url}/api/search?q=${encodeURIComponent('ＣＡＬＭ')}`)).json();
 assert.deepEqual(found.results.map(r=>[r.kind,r.goalId,r.goalTitle]),[['goal','1','Searchable calm Goal']]);
 assert.deepEqual((await (await fetch(`${url}/api/search`)).json()).results,[]);
 assert.equal((await fetch(`${url}/api/search?q=calm`,{method:'POST',headers:{Origin:url,'Content-Type':'application/json'},body:'{}'})).status,405);
});
